"""
Local pool-based batch fit runner for the M2 analysis.

Reads a fit_params.tsv (generated by ``gen_params.py fit``) and runs all
parameter points using a ``multiprocessing.Pool``, calling
``setup_and_run`` directly in each worker process.

Memory management: each pool worker is an isolated OS process.
``maxtasksperchild=1`` forces each worker to exit after one fit, so all
PyMC / PyTensor memory is released by the OS before the next fit starts.

Usage::

    # Run sequentially (safe default — each fit already uses ~8 threads)
    python -m qpym2.run.run_fits -p scripts/params/fit_params.tsv

    # Run up to 3 fits in parallel
    python -m qpym2.run.run_fits -p scripts/params/fit_params.tsv --njobs 3

    # Preview jobs without running
    python -m qpym2.run.run_fits -p scripts/params/fit_params.tsv --dry-run

Flags not yet exposed (blinded, skip_roi, etc.) can be added later; the
worker and TSV reader are written to make that straightforward.
"""

import argparse
import csv
import traceback
from multiprocessing import Pool

from qpym2.cfg.hydra_adapter import get_config
from qpym2.cfg.config_builders import (
    get_fit_dir, get_h2uv_model, get_comp_cfg,
    get_data_names, get_jags_path,
)
from qpym2.io.bkg_model import read_mkchain
from qpym2.fit.params import model_cfg as build_model_cfg
from qpym2.run.run_single_fit import setup_and_run


# ---------------------------------------------------------------------------
# Pool worker  (must be module-level for multiprocessing pickling)
# ---------------------------------------------------------------------------

def _run_fit_job(job):
    """Run one fit in-process inside a fresh worker process.

    All heavy objects (Hydra config, h2uv model, mksamples) are loaded
    locally so nothing is shared or pickled across process boundaries.

    Args:
        job (dict): Keys: task_id, co_cut, ndbd_cutoff, co_shift,
            environment, chains, draws, mkchain_samples, write.

    Returns:
        tuple: (task_id, error_str or None)
    """
    task_id = job['task_id']
    try:
        model_key = job.get('model_key', 'default')
        cfg = get_config(environment=job['environment'])
        fit_dir = get_fit_dir(cfg)
        h2uv_model = get_h2uv_model(cfg, model_key=model_key)
        comp_cfg = get_comp_cfg(cfg, model_key=model_key)
        data_name, data_blinded_name = get_data_names(cfg)
        jags_fpath = get_jags_path(cfg)
        naming = cfg.infrastructure.naming_conventions

        mksamples = read_mkchain(jags_fpath).sample(n=job['mkchain_samples']).T

        mcfg = build_model_cfg(
            h2uv_model,
            co_cut=job['co_cut'],
            ndbd_cutoff=job['ndbd_cutoff'],
            co_shift=job['co_shift'],
            blinded=False,
            skip_roi=False,
        )
        fitdir = f"{fit_dir}/{mcfg['dir_name']}"

        print(f"[task {task_id}] starting: {mcfg['name']}")
        setup_and_run(
            fitdir, mcfg, data_name, data_blinded_name,
            mksamples=mksamples,
            write=job.get('write', True),
            comp_cfg=comp_cfg,
            chains=job['chains'],
            draws=job['draws'],
            input_name=naming.get('input_name', 'input'),
            input_noroi_name=naming.get('input_noroi_name', 'input_noroi'),
        )
        print(f"[task {task_id}] done: {mcfg['name']}")
        return task_id, None

    except Exception:
        err = traceback.format_exc()
        print(f"[task {task_id}] FAILED:\n{err}")
        return task_id, err


# ---------------------------------------------------------------------------
# TSV reader
# ---------------------------------------------------------------------------

def read_fit_params(tsv_path):
    """Read a fit_params.tsv and return a list of parsed row dicts.

    Normalises 'None' / 'null' / '' strings to Python None and casts
    co_shift to float.

    Args:
        tsv_path (str): Path to the TSV file.

    Returns:
        list[dict]: One dict per row with keys: task_id, co_cut,
            ndbd_cutoff, co_shift.
    """
    def _none(v):
        return None if v in ('None', 'null', '') else v

    rows = []
    with open(tsv_path, newline='') as f:
        for row in csv.DictReader(f, delimiter='\t'):
            rows.append({
                'task_id':     int(row['task_id']),
                'co_cut':      _none(row['co_cut']),
                'ndbd_cutoff': _none(row['ndbd_cutoff']),
                'co_shift':    float(row['co_shift']),
            })
    return rows


# ---------------------------------------------------------------------------
# Orchestrator
# ---------------------------------------------------------------------------

def run_fits(tsv_path, environment='tech_note', njobs=1,
             chains=8, draws=20000, mkchain_samples=100,
             write=True, dry_run=False):
    """Run all fits listed in a fit_params.tsv using a local process pool.

    Args:
        tsv_path (str): Path to the params TSV.
        environment (str): Hydra environment name (default: 'tech_note').
        njobs (int): Number of parallel fit processes (default: 1).
            Set > 1 only if the machine has enough memory; each fit
            internally spawns ~chains threads.
        chains (int): MCMC chains per fit (default: 8).
        draws (int): MCMC draws per chain (default: 20000).
        mkchain_samples (int): JAGS samples for prior generation (default: 100).
        write (bool): Write fit results to disk (default: True).
        dry_run (bool): Print jobs without running (default: False).
    """
    rows = read_fit_params(tsv_path)
    jobs = [
        {**row,
         'environment':     environment,
         'chains':          chains,
         'draws':           draws,
         'mkchain_samples': mkchain_samples,
         'write':           write}
        for row in rows
    ]

    if dry_run:
        print(f"Dry run — {len(jobs)} jobs:")
        for job in jobs:
            print(f"  task {job['task_id']:3d}"
                  f"  co_cut={job['co_cut']}"
                  f"  ndbd_cutoff={job['ndbd_cutoff']}"
                  f"  co_shift={job['co_shift']}"
                  f"  env={job['environment']}"
                  f"  chains={job['chains']}  draws={job['draws']}")
        return

    n = len(jobs)
    print(f"[run_fits] {n} job(s)  njobs={njobs}  environment={environment}"
          f"  chains={chains}  draws={draws}")

    failures = []
    completed = 0
    with Pool(processes=njobs, maxtasksperchild=1) as pool:
        for task_id, err in pool.imap_unordered(_run_fit_job, jobs):
            completed += 1
            status = 'FAILED' if err else 'done'
            print(f"[run_fits] [{completed}/{n}] task {task_id} {status}")
            if err:
                failures.append((task_id, err))

    if failures:
        print(f"\n[run_fits] {len(failures)} fit(s) failed:")
        for tid, err in failures:
            print(f"  task {tid}:\n{err}")
    else:
        print(f"\n[run_fits] all {n} fits completed successfully")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def parse_args():
    parser = argparse.ArgumentParser(
        description='Run all fits in a fit_params.tsv using a local process pool.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""\
Examples:
  python -m qpym2.run.run_fits -p scripts/params/fit_params.tsv
  python -m qpym2.run.run_fits -p scripts/params/fit_params.tsv --njobs 3
  python -m qpym2.run.run_fits -p scripts/params/fit_params.tsv --dry-run
        """,
    )
    parser.add_argument('--params', '-p', required=True,
                        help='Path to fit_params.tsv')
    parser.add_argument('--njobs', '-n', type=int, default=1,
                        help='Number of parallel fit processes (default: 1)')
    parser.add_argument('--environment', '-e', default='tech_note',
                        help='Hydra environment config name (default: tech_note)')
    parser.add_argument('--chains', type=int, default=8,
                        help='MCMC chains per fit (default: 8)')
    parser.add_argument('--draws', type=int, default=20000,
                        help='MCMC draws per chain (default: 20000)')
    parser.add_argument('--mkchain-samples', type=int, default=100,
                        help='JAGS samples for prior generation (default: 100)')
    parser.add_argument('--no-write', action='store_true', default=False,
                        help='Disable writing fit results to disk')
    parser.add_argument('--dry-run', action='store_true', default=False,
                        help='Print jobs without running')
    return parser.parse_args()


def main():
    args = parse_args()
    run_fits(
        tsv_path=args.params,
        environment=args.environment,
        njobs=args.njobs,
        chains=args.chains,
        draws=args.draws,
        mkchain_samples=args.mkchain_samples,
        write=not args.no_write,
        dry_run=args.dry_run,
    )


if __name__ == '__main__':
    main()

